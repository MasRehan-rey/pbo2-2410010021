    private void npmFieldKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_npmFieldKeyTyped
    char karakter = evt.getKeyChar();

// Cegah input selain angka
if (!Character.isDigit(karakter)
        && karakter != KeyEvent.VK_BACK_SPACE
        && karakter != KeyEvent.VK_DELETE) {
    evt.consume();
}

// Batasi maksimal 10 digit
if (npmField.getText().length() >= 10
        && karakter != KeyEvent.VK_BACK_SPACE
        && karakter != KeyEvent.VK_DELETE
        && npmField.getSelectedText() == null) {
    evt.consume();
}        // TODO add your handling code here:
    }//GEN-LAST:event_npmFieldKeyTyped

