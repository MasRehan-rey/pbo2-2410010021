  private boolean periksaNpm() {
    return tandai(
        npmField,
        npmErrorLabel,
        ValidatorPerpustakaan.npm(npmField.getText())
    );
}
    
    private boolean periksaNama() {
    return tandai(
        namaField,
        namaPesanLabel,
        ValidatorPerpustakaan.nama(namaField.getText())
    );
}
    
   private boolean periksaProdi() {
    String kesalahan = null;

    if (programStudiCombo.getSelectedIndex() == 0) {
        kesalahan = "Pilih salah satu program studi";
    }

    return tandai(
        programStudiCombo,
        prodiPesanLabel,
        kesalahan
    );
}
    
    private boolean periksaEmail() {
    return tandai(
        emailField,
        emailPesanLabel,
        ValidatorPerpustakaan.email(emailField.getText())
    );
}
    
    private boolean periksaHp() {
    return tandai(
        hpField,
        hpPesanLabel,
        ValidatorPerpustakaan.nomorHp(hpField.getText())
    );
}
    
    private boolean tandai(
        JComponent isian,
        JLabel pesan,
        String kesalahan) {

    isian.putClientProperty(
        "JComponent.outline",
        (kesalahan == null) ? null : "error"
    );

    pesan.setText(
        (kesalahan == null) ? " " : kesalahan
    );

    return kesalahan == null;
}
    
    private void daftar() {
    List<JComponent> salah = new ArrayList<>();

    if (!periksaNpm()) {
        salah.add(npmField);
    }

    if (!periksaNama()) {
        salah.add(namaField);
    }

    if (!periksaProdi()) {
        salah.add(programStudiCombo);
    }

    if (!periksaEmail()) {
        salah.add(emailField);
    }

    if (!periksaHp()) {
        salah.add(hpField);
    }

    if (!salah.isEmpty()) {
        statusLabel.setText(
            salah.size() + " isian perlu diperbaiki"
        );

        salah.get(0).requestFocusInWindow();
        return;
    }

    statusLabel.setText("Data berhasil divalidasi");

javax.swing.JOptionPane.showMessageDialog(
        this,
        "Pendaftaran Anggota Perpustakaan\n"
        + "NPM: " + npmField.getText().trim() + "\n"
        + "Nama: " + namaField.getText().trim() + "\n"
        + "Program Studi: " + programStudiCombo.getSelectedItem() + "\n"
        + "Jenis Anggota: " + jenisAnggota(),
        "Ringkasan Pendaftaran",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
);
}
    
    private String jenisAnggota() {
    if (mahasiswaRadio.isSelected()) {
        return "Mahasiswa";
    } else if (dosenRadio.isSelected()) {
        return "Dosen";
    } else if (umumRadio.isSelected()) {
        return "Umum";
    }

    return "";
}
    
    private boolean adaIsian() {
    return !npmField.getText().isBlank()
            || !namaField.getText().isBlank()
            || programStudiCombo.getSelectedIndex() != 0
            || !emailField.getText().isBlank()
            || !hpField.getText().isBlank()
            || !alamatArea.getText().isBlank()
            || !jenisAnggota().isBlank()
            || setujuCheck.isSelected();
}
    
    private void kosongkan() {
    npmField.setText("");
    namaField.setText("");
    programStudiCombo.setSelectedIndex(0);
    emailField.setText("");
    hpField.setText("");
    alamatArea.setText("");

    jenisAnggotaButtonGroup.clearSelection();
    setujuCheck.setSelected(false);

    digitLabel.setText("0 dari 10 digit");
    statusLabel.setText(" ");

    periksaNpm();
    periksaNama();
    periksaProdi();
    periksaEmail();
    periksaHp();

    npmField.requestFocusInWindow();
}
    private void batal() {
    if (adaIsian()) {
        int jawab = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Apakah kamu yakin ingin mengosongkan form?",
                "Konfirmasi",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (jawab == javax.swing.JOptionPane.YES_OPTION) {
            kosongkan();
        }
    } else {
        kosongkan();
    }
}
