private void simpan() {

    String kode = kodeField.getText().trim();
    String judul = judulField.getText().trim();
    String penulis = penulisField.getText().trim();
    String tahunText = tahunField.getText().trim();

    if (kode.isEmpty()) {
        pesanLabel.setText("Kode buku wajib diisi");
        kodeField.requestFocusInWindow();
        return;
    }

    if (judul.isEmpty()) {
        pesanLabel.setText("Judul buku wajib diisi");
        judulField.requestFocusInWindow();
        return;
    }

    if (tahunText.isEmpty()) {
        pesanLabel.setText("Tahun terbit wajib diisi");
        tahunField.requestFocusInWindow();
        return;
    }

    int tahun;

    try {
        tahun = Integer.parseInt(tahunText);
    } catch (NumberFormatException e) {
        pesanLabel.setText("Tahun harus berupa angka");
        tahunField.requestFocusInWindow();
        return;
    }

    int tahunSekarang = Year.now().getValue();

    if (tahun < 1900 || tahun > tahunSekarang) {
        pesanLabel.setText(
                "Tahun harus antara 1900 sampai " + tahunSekarang
        );
        tahunField.requestFocusInWindow();
        return;
    }

    StatusBuku status =
            (StatusBuku) statusCombo.getSelectedItem();

    hasil = new Buku(
            kode,
            judul,
            penulis,
            tahun,
            status
    );

    dispose();
}

    public Buku tampilkan() {
        setVisible(true);
        return hasil;
    }

